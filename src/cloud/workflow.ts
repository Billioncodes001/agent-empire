/**
 * CLOUD-02 workflow template committed into the user's private state repository. Secrets appear only
 * as `env:` values of the single coordinator step; nothing echoes them.
 */
export const WORKFLOW_FILE = 'agent-empire.yml';
export const WORKFLOW_PATH = `.github/workflows/${WORKFLOW_FILE}`;
export const COORDINATOR_BUNDLE_PATH = 'coordinator/agent-empire-coordinator.mjs';
export const DISPATCH_TYPES = ['agent-empire-intent', 'agent-empire-start', 'agent-empire-shutdown'] as const;

export interface WorkflowOptions {
  /** Five-field cron; GitHub may delay scheduled runs. Default every 10 minutes. */
  cron?: string;
  nodeVersion?: string;
  /**
   * Adds `actions: write` so the coordinator can disable its own workflow after shutdown (CLOUD-05).
   * Without it the permissions are `contents: write` only and the app disables the workflow instead.
   */
  allowSelfDisable?: boolean;
}

export function coordinatorWorkflow(options: WorkflowOptions = {}): string {
  const cron = options.cron ?? '*/10 * * * *';
  if (!/^[0-9*/,-]+( [0-9*/,-]+){4}$/.test(cron)) throw new Error('Invalid cron expression');
  const node = options.nodeVersion ?? '22';
  if (!/^\d{2}$/.test(node)) throw new Error('Invalid Node.js major version');
  const selfDisable = options.allowSelfDisable ?? true;
  return `# Agent Empire coordinator. Generated by the Agent Empire installer; edits may be overwritten.
# Runs one coordinator tick: applies intents, polls provider sessions, enforces spending limits,
# dispatches queued jobs and commits the new state. One run at a time.
name: Agent Empire coordinator

on:
  schedule:
    - cron: '${cron}'
  workflow_dispatch:
  repository_dispatch:
    types: [${DISPATCH_TYPES.join(', ')}]

concurrency:
  group: agent-empire
  cancel-in-progress: false

permissions:
  contents: write${selfDisable ? `
  actions: write # only used to disable this workflow after an explicit shutdown` : ''}

jobs:
  tick:
    runs-on: ubuntu-latest
    timeout-minutes: 8
    steps:
      - uses: actions/checkout@v4
        with:
          persist-credentials: false
          sparse-checkout: coordinator
      - uses: actions/setup-node@v4
        with:
          node-version: '${node}'
      - name: Coordinator tick
        run: node ${COORDINATOR_BUNDLE_PATH} tick
        env:
          GITHUB_TOKEN: \${{ github.token }}
          ANTHROPIC_API_KEY: \${{ secrets.ANTHROPIC_API_KEY }}
          OPENAI_API_KEY: \${{ secrets.OPENAI_API_KEY }}
          PROJECT_GITHUB_TOKEN: \${{ secrets.PROJECT_GITHUB_TOKEN }}
          AGENT_EMPIRE_WORKFLOW: ${WORKFLOW_FILE}
          AGENT_EMPIRE_SELF_DISABLE: '${selfDisable ? 'true' : 'false'}'
`;
}
